CREATE TABLE salas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(80) NOT NULL,
    codigo VARCHAR(12) NOT NULL UNIQUE,
    professor_id BIGINT NOT NULL REFERENCES users(id)
);
CREATE INDEX salas_professor_idx ON salas(professor_id);

CREATE TABLE sala_alunos (
    aluno_id BIGINT PRIMARY KEY REFERENCES users(id),
    sala_id BIGINT NOT NULL REFERENCES salas(id)
);
CREATE INDEX sala_alunos_sala_idx ON sala_alunos(sala_id);

CREATE TABLE sala_atividades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sala_id BIGINT NOT NULL REFERENCES salas(id),
    titulo VARCHAR(200) NOT NULL,
    descricao VARCHAR(4000),
    prazo TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX sala_atividades_sala_idx ON sala_atividades(sala_id);
ALTER TABLE tarefas ADD COLUMN sala_atividade_id BIGINT REFERENCES sala_atividades(id);
ALTER TABLE tarefas ADD CONSTRAINT tarefas_sala_aluno_unique UNIQUE (owner_id, sala_atividade_id);
